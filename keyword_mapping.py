# 反向索引：中文变体 → 英文词条
CHINESE_TO_ENGLISH = {}
for english, chinese_list in KEYWORD_MAPPING.items():
    for chinese in chinese_list:
        CHINESE_TO_ENGLISH[chinese] = english

def parse_input(chinese_input):
    """
    智能拆解中文输入，支持模糊匹配
    例如："白发蓝瞳美少女" → ['white hair', 'blue eyes', '1girl']
    """
    results = []
    remaining = chinese_input
    
    # 1. 优先匹配长关键词（避免"白色头发"被拆成"白色"+"头发"）
    sorted_keywords = sorted(CHINESE_TO_ENGLISH.keys(), key=len, reverse=True)
    
    for keyword in sorted_keywords:
        if keyword in remaining:
            english = CHINESE_TO_ENGLISH[keyword]
            results.append({
                'keyword': keyword,
                'english': english,
                'chinese': keyword,
                'matched_by': 'exact'
            })
            remaining = remaining.replace(keyword, '')
    
    # 2. 如果还有剩余内容，尝试模糊匹配（子串匹配）
    if remaining:
        # 尝试从剩余内容中提取可能的关键词
        for keyword in sorted_keywords:
            if len(keyword) >= 2:  # 至少 2 个字
                for i in range(len(keyword) - 1):
                    sub = keyword[i:i+2]
                    if sub in remaining:
                        english = CHINESE_TO_ENGLISH[keyword]
                        # 避免重复
                        if not any(r['english'] == english for r in results):
                            results.append({
                                'keyword': sub,
                                'english': english,
                                'chinese': f"{keyword} (包含'{sub}')",
                                'matched_by': 'fuzzy'
                            })
    
    # 3. 去重并保持顺序
    seen = set()
    unique_results = []
    for r in results:
        if r['english'] not in seen:
            seen.add(r['english'])
            unique_results.append(r)
    
    return unique_results, remaining
